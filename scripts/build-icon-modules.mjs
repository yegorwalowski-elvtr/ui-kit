/**
 * Inlines every SVG under src/assets/icons/ into a plain TypeScript module.
 *
 * The kit used to read these with Vite's `?raw` import, which forced every
 * consumer onto Vite. Emitting a normal .ts module instead keeps the kit
 * bundler-agnostic (Next.js, webpack, Rollup, tsc) while the .svg files stay
 * the source of truth designers export to.
 *
 * Run after adding or re-exporting an icon:  npm run build:icons
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const ICONS_DIR = fileURLToPath(new URL("../src/assets/icons", import.meta.url))
const OUT_FILE = join(ICONS_DIR, "svg-sources.ts")

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) return walk(path)
    return entry.name.endsWith(".svg") ? [path] : []
  })
}

const files = walk(ICONS_DIR).sort()
const entries = files.map((file) => {
  // "vuesax-bulk/calendar.svg" → "vuesax-bulk/calendar"
  const key = relative(ICONS_DIR, file).replace(/\\/g, "/").replace(/\.svg$/, "")
  const svg = readFileSync(file, "utf8").trim()
  return `  ${JSON.stringify(key)}: ${JSON.stringify(svg)},`
})

writeFileSync(
  OUT_FILE,
  `/* GENERATED by scripts/build-icon-modules.mjs — do not edit.
 * Source of truth: the .svg files in this directory. Re-run \`npm run build:icons\`
 * after adding or re-exporting an icon.
 */

export const svgSources = {
${entries.join("\n")}
} as const

export type SvgSourceKey = keyof typeof svgSources
`,
  "utf8"
)

console.log(`wrote ${relative(process.cwd(), OUT_FILE)} (${files.length} icons)`)
